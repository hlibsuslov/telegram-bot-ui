# ---------------------------------------------------------------- inputs

def read(rel: str) -> str:
    with open(os.path.join(ROOT, rel), encoding="utf-8") as fh:
        return fh.read().replace("\r\n", "\n")


def load_routing() -> dict:
    return json.loads(read("adapters/routing.json"))


def split_front_matter(text: str) -> tuple[str, str]:
    if not text.startswith("---"):
        raise ValueError("SKILL.md has no front matter")
    end = text.find("\n---", 3)
    return text[3:end].strip("\n"), text[end + 4:]


def parse_front_matter(fm: str) -> dict[str, str]:
    """Minimal parser for `key: value` and folded/literal block scalars.

    Deliberately independent of PyYAML so the output is identical on every machine.
    """
    result: dict[str, str] = {}
    lines = fm.splitlines()
    i = 0
    while i < len(lines):
        m = re.match(r"^([A-Za-z0-9_-]+):\s*(.*)$", lines[i])
        if not m:
            i += 1
            continue
        key, val = m.group(1), m.group(2).strip()
        if val in (">", ">-", "|", "|-", ">+", "|+"):
            block: list[str] = []
            i += 1
            while i < len(lines) and (not lines[i].strip() or lines[i][:1] in (" ", "\t")):
                block.append(lines[i].strip())
                i += 1
            sep = " " if val.startswith(">") else "\n"
            result[key] = sep.join(b for b in block if b).strip()
            continue
        result[key] = val.strip('"').strip("'")
        i += 1
    return result


def skill_sections(body: str) -> list[tuple[str, str]]:
    """Return (heading, text) for every `## ` section of the SKILL.md body."""
    sections: list[tuple[str, str]] = []
    heading, buf, fence = None, [], False
    for line in body.split("\n"):
        if line.startswith("```"):
            fence = not fence
        if not fence and line.startswith("## "):
            if heading is not None:
                sections.append((heading, "\n".join(buf).strip("\n")))
            heading, buf = line[3:].strip(), []
        elif heading is not None:
            buf.append(line)
    if heading is not None:
        sections.append((heading, "\n".join(buf).strip("\n")))
    return sections


def load_skill() -> tuple[dict[str, str], list[tuple[str, str]]]:
    fm, body = split_front_matter(read(f"{SKILL_REL}/SKILL.md"))
    return parse_front_matter(fm), skill_sections(body)


def load_commands() -> dict:
    return json.loads(read(f"{SKILL_REL}/commands/index.json"))


CMD_BEGIN = "<!-- commands:begin"
CMD_END = "<!-- commands:end -->"


def commands_table(cmds: dict) -> str:
    rows = ["| Verb | Sounds like | Does |", "|---|---|---|"]
    for c in cmds["commands"]:
        said = c["sounds_like"]
        phrases = said["en"][:2] + said.get("ru", [])[:1] + said.get("uk", [])[:1]
        quoted = "; ".join(p if p.startswith("no request") else f'"{p}"' for p in phrases)
        rows.append(f"| `{c['verb']}` | {quoted} | {c['short']} |")
    return "\n".join(rows)


def render_skill_md(cmds: dict) -> str:
    text = read(f"{SKILL_REL}/SKILL.md")
    if text.count(CMD_BEGIN) != 1 or text.count(CMD_END) != 1:
        raise ValueError("SKILL.md needs exactly one commands:begin / commands:end block")
    head_end = text.index("\n", text.index(CMD_BEGIN)) + 1
    return text[:head_end] + commands_table(cmds) + "\n" + text[text.index(CMD_END):]


def reference_front_matter(rel: str) -> dict[str, str]:
    text = read(f"{SKILL_REL}/{rel}")
    return parse_front_matter(split_front_matter(text)[0]) if text.startswith("---") else {}


def render_reference_index(cmds: dict) -> str:
    routed: dict[str, list[str]] = {}
    for c in cmds["commands"]:
        for ref in c["refs"]:
            routed.setdefault(ref, []).append(c["verb"])
    base = os.path.join(SKILL_DIR, "references")
    rels = []
    for dirpath, _dirs, files in os.walk(base):
        for name in files:
            if name.endswith(".md") and name != "INDEX.md":
                rels.append(os.path.relpath(os.path.join(dirpath, name), SKILL_DIR).replace(os.sep, "/"))
    rels.sort(key=lambda r: (r.count("/"), r))
    dates, rows = [], []
    for rel in rels:
        fm = reference_front_matter(rel)
        if fm.get("verified"):
            dates.append(fm["verified"])
        summary = fm.get("summary") or doc_title_and_note(f"{SKILL_REL}/{rel}")[1]
        if rel == "references/floor.md":
            verbs = "all, before the first edit"
        else:
            verbs = ", ".join(routed.get(rel, [])) or "-"
        rows.append(f"| `{rel[len('references/'):]}` | {summary.replace('|', '/')} | {verbs} |")
    out = ["---",
           'summary: "Every reference file with its one-line summary and the commands that route to it; generated."',
           f'verified: "{max(dates) if dates else "2026-11-25"}"',
           'bot_api: "10.5"',
           "---",
           "# References index",
           "",
           "<!-- Generated by scripts/build_adapters.py from each file's front matter and "
           "commands/index.json; do not edit. -->",
           "",
           "Read a file only when its command's playbook points to it; long files open with a contents list.",
           "",
           "| File | What it covers | Commands |",
           "|---|---|---|",
           *rows]
    return "\n".join(out) + "\n"


def exists(rel: str) -> bool:
    """`rel` is relative to the skill folder, like every path in the capability docs."""
    return os.path.exists(os.path.join(SKILL_DIR, rel.rstrip("/")))


# ---------------------------------------------------------------- rendering helpers

def yaml_str(value: str) -> str:
    # A JSON string is a valid YAML double-quoted scalar.
    return json.dumps(value, ensure_ascii=False)


def toml_str(value: str) -> str:
    # JSON escapes (\" \\ \n \uXXXX) are all valid in a TOML basic string.
    return json.dumps(value, ensure_ascii=True)


def role_docs(role: dict) -> list[tuple[str, str]]:
    by_verb = {c["verb"]: c for c in load_commands()["commands"]}
    docs = [("SKILL.md", "entry point: Start steps, command table, invariants"),
            ("references/floor.md", "read before the first edit")]
    docs += [(by_verb[v]["playbook"], f"`{v}`: {by_verb[v]['short']}") for v in role["verbs"]]
    return docs


