# ---------------------------------------------------------------- outputs

def build() -> dict[str, str]:
    routing = load_routing()
    meta, sections = load_skill()
    if meta.get("name") != routing["skill"]:
        raise ValueError("SKILL.md name and adapters/routing.json skill differ")
    cmds = load_commands()
    out: dict[str, str] = {
        f"{SKILL_REL}/SKILL.md": render_skill_md(cmds),
        f"{SKILL_REL}/references/INDEX.md": render_reference_index(cmds),
        f"{SKILL_REL}/agents/openai.yaml": render_openai_yaml(routing, meta),
        "adapters/agents-md/AGENTS.snippet.md": render_pointer(routing, "agents-md"),
        "adapters/cursor/telegram-bot-ui.mdc": render_pointer(routing, "cursor"),
        "adapters/gemini/GEMINI.md": render_pointer(routing, "gemini"),
        "adapters/copilot/copilot-instructions.md": render_pointer(routing, "copilot"),
        "adapters/portable/telegram-bot-ui.prompt.md": render_portable(routing, meta, sections),
        ".claude-plugin/plugin.json": render_plugin(routing),
        ".claude-plugin/marketplace.json": render_marketplace(routing),
        "plugin.json": render_agent_plugin(routing),
        ".codex-plugin/plugin.json": render_codex_plugin(routing),
        "gemini-extension.json": render_gemini_extension(routing),
        # Installers copy only the skill folder, so it carries its own LICENSE.
        f"{SKILL_REL}/LICENSE": read("LICENSE"),
    }
    for role in routing["roles"]:
        out[f"agents/claude/{role['name']}.md"] = render_claude_agent(routing, role)
        out[f"agents/codex/{codex_name(role)}.toml"] = render_codex_agent(routing, role)
    # llms.txt indexes the other outputs too, so render it after they exist on disk.
    out["llms.txt"] = render_llms(routing, meta)
    return dict(sorted(out.items()))


GENERATED_DIRS = {"agents/claude": ".md", "agents/codex": ".toml"}


def orphans(outputs: dict[str, str]) -> list[str]:
    found = []
    for folder, ext in GENERATED_DIRS.items():
        base = os.path.join(ROOT, folder)
        if os.path.isdir(base):
            found += [f"{folder}/{n}" for n in sorted(os.listdir(base))
                      if n.endswith(ext) and f"{folder}/{n}" not in outputs]
    return found


def stale(outputs: dict[str, str]) -> list[str]:
    bad = []
    for rel, content in outputs.items():
        path = os.path.join(ROOT, rel)
        if not os.path.isfile(path) or read(rel) != content:
            bad.append(rel)
    return bad + orphans(outputs)


def write(outputs: dict[str, str]) -> list[str]:
    changed = []
    for rel, content in outputs.items():
        path = os.path.join(ROOT, rel)
        if os.path.isfile(path) and read(rel) == content:
            continue
        os.makedirs(os.path.dirname(path) or ROOT, exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(content)
        changed.append(rel)
    for rel in orphans(outputs):
        os.remove(os.path.join(ROOT, rel))
        changed.append(f"{rel} (removed)")
    return changed


def missing_routed_paths() -> list[str]:
    cmds = load_commands()["commands"]
    paths = sorted({p for c in cmds for p in [c["playbook"], *c["refs"]]} | {"references/floor.md"})
    return [p for p in paths if not exists(p)]


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="fail if generated files are stale")
    ap.add_argument("--report", action="store_true", help="list routed paths missing here")
    args = ap.parse_args(argv)
    if args.report:
        missing = missing_routed_paths()
        print("\n".join(f"missing: {p}" for p in missing) or "all routed paths exist")
        return 0
    # Two passes: llms.txt lists generated files, so the first write can change its input.
    outputs = build()
    if args.check:
        bad = stale(outputs)
        if bad:
            print("Stale adapters (run `python scripts/build_adapters.py`):")
            print("\n".join(f"  {b}" for b in bad))
            return 1
        print(f"OK: {len(outputs)} generated adapter files are up to date.")
        return 0
    changed = write(outputs)
    changed += [c for c in write(build()) if c not in changed]
    print("\n".join(f"wrote {c}" for c in changed) or "no changes")
    # The website's agent docs derive from the same sources: regenerate them in the same step.
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    import build_agent_docs  # noqa: PLC0415
    return build_agent_docs.main([])


if __name__ == "__main__":
    sys.exit(main())
