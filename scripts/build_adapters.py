"""Generate every host-specific entry file from SKILL.md and adapters/routing.json.

  python scripts/build_adapters.py            # write the generated files
  python scripts/build_adapters.py --check    # exit 1 if any generated file is stale
  python scripts/build_adapters.py --report   # list routed paths missing in this checkout

Sources of truth: SKILL.md (front matter and sections), skills/telegram-bot-ui/commands/index.json
(commands: phrases, playbooks, references, roles), adapters/routing.json (roles, packaging
metadata) and adapters/source/roles/*.md (role bodies). SKILL.md is also an output: its command
table between the `commands:begin` and `commands:end` markers is rendered from the index, and
references/INDEX.md is rendered from the references' front matter.
Outputs are listed in OUTPUTS below; docs/hosts.md explains each host format.
Standard library only, deterministic (sorted, LF line endings), no network.
"""
