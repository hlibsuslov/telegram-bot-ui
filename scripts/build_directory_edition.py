"""Build the documentation-only edition of the plugin for the Claude plugin directory.

The directory accepts only Markdown, text, JSON, YAML and raster images from
organizations it has not verified, so this edition keeps the skill's instructions,
references, recipes, the JSON Bot API catalog and the Claude subagents, and leaves out
the scripts and runnable examples. `.github/workflows/directory-edition.yml` publishes
it to the `claude-directory` branch, which the directory tracks.

  python scripts/build_directory_edition.py build <out-dir>
  python scripts/build_directory_edition.py --check   # build into a temp dir and verify
"""
# run-checks: --check
from __future__ import annotations

import argparse
import json
import os
import shutil
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SKILL_REL = "skills/telegram-bot-ui"
REPO_URL = "https://github.com/hlibsuslov/telegram-bot-ui"

ALLOWED_EXT = {".md", ".txt", ".json", ".yaml", ".yml", ".png", ".jpg", ".jpeg", ".gif", ".webp", ".ico"}
IMAGE_EXT = {".png", ".jpg", ".jpeg", ".gif", ".webp", ".ico"}
# Allowed by extension but refused as package-manager or build configuration.
EXCLUDED_NAMES = {"package.json", "package-lock.json", "pnpm-workspace.yaml", "yarn.lock",
                  "requirements.txt", "tsconfig.json"}

# (source relative to ROOT, destination relative to the edition root)
COPIED_FILES = [
    (".claude-plugin/plugin.json", ".claude-plugin/plugin.json"),
    ("assets/icon.png", "assets/icon.png"),
    ("LICENSE", "LICENSE"),
    ("PRIVACY.md", "PRIVACY.md"),
    ("SECURITY.md", "SECURITY.md"),
]
COPIED_TREES = [SKILL_REL, "agents/claude"]

SYMBOLS_REL = f"{SKILL_REL}/data/bot-api/symbols"
LOOKUP_HINT = (
    "look up one method in `data/bot-api/symbols/methods/<method>.json` or one type in "
    "`data/bot-api/symbols/types/<Type>.json` (names and sections in "
    "`data/bot-api/symbols/index.json`); field limits are in each field's official description "
    "(for example `InlineKeyboardButton.callback_data`: 1-64 bytes), and message and caption "
    "limits are in `references/limits-and-splitting.md`"
)
EDITION_NOTE = (
    "> **Directory edition.** This copy is the documentation-only build published to the Claude "
    "plugin directory. It ships without `scripts/` and the runnable code in `examples/` (Python, "
    "TypeScript, widget kits). Where a step below names a script, do the same check by hand: "
    f"{LOOKUP_HINT}. Count `callback_data` and other byte limits in UTF-8 bytes, not characters. "
    "If the user wants the validators, publishing and widget tools, tell them the full toolset "
    f"installs from {REPO_URL}."
)
TOOLS_NOTE = (
    f"> Not bundled in the directory edition; the full version at {REPO_URL} has them. "
    f"Without them, {LOOKUP_HINT}."
)

README = f"""# Telegram Bot UI (directory edition)

A UI/UX skill for Telegram bots, updated for every Bot API release: screens, keyboards,
colored buttons, streaming AI replies with Stop, Rich Messages, HTML widgets, channel
publishing and agent-operated bots, with an offline Bot API catalog in JSON.

This is the documentation-only build for the Claude plugin directory: the skill, its
references and recipes, and five subagents, without the scripts and runnable examples.
The full version, with validators, a publishing tool and widget kits, is at
<{REPO_URL}>; in Claude Code it installs with:

```
/plugin install telegram-bot-ui --marketplace hlibsuslov/telegram-bot-ui
```

Generated by `scripts/build_directory_edition.py`; do not edit this branch by hand.

License: MIT. Privacy: [PRIVACY.md](PRIVACY.md).
"""


def _keep(path: str) -> bool:
    name = os.path.basename(path)
    ext = os.path.splitext(name)[1].lower()
    return name == "LICENSE" or (ext in ALLOWED_EXT and name not in EXCLUDED_NAMES)


def _copy(src_rel: str, dst_rel: str, out: str) -> None:
    dst = os.path.join(out, *dst_rel.split("/"))
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    shutil.copyfile(os.path.join(ROOT, *src_rel.split("/")), dst)


def _annotate_skill(out: str) -> None:
    path = os.path.join(out, *SKILL_REL.split("/"), "SKILL.md")
    with open(path, encoding="utf-8") as fh:
        text = fh.read()
    title = "\n# Telegram Bot UI\n"
    tools = "\n## Tools (offline, stdlib, no token)\n"
    if text.count(title) != 1 or text.count(tools) != 1:
        raise SystemExit("SKILL.md layout changed: update the anchors in build_directory_edition.py")
    text = text.replace(title, f"{title}\n{EDITION_NOTE}\n", 1)
    text = text.replace(tools, f"{tools}\n{TOOLS_NOTE}\n", 1)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)


def _write_json(path: str, data: object) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        json.dump(data, fh, ensure_ascii=False, indent=1)
        fh.write("\n")


def _write_symbols(out: str) -> None:
    """Split the 1 MB catalog into one small file per method and type, plus an index.

    Without the lookup script, and in Claude apps that can't read a 1 MB file, the agent
    can still open exactly the method or type it needs.
    """
    with open(os.path.join(ROOT, *SKILL_REL.split("/"), "data", "bot-api", "catalog.json"),
              encoding="utf-8") as fh:
        catalog = json.load(fh)
    base = os.path.join(out, *SYMBOLS_REL.split("/"))
    index = {"bot_api_version": catalog["meta"]["bot_api_version"],
             "release_date": catalog["meta"]["release_date"],
             "source": catalog["meta"]["source"], "methods": {}, "types": {}}
    for group in ("methods", "types"):
        for name, entry in sorted(catalog[group].items()):
            _write_json(os.path.join(base, group, f"{name}.json"), entry)
            index[group][name] = entry.get("section", "")
    _write_json(os.path.join(base, "index.json"), index)


def build(out: str) -> list[str]:
    """Write the edition into `out` (created or emptied) and return its files, relative."""
    if os.path.isdir(out):
        shutil.rmtree(out)
    os.makedirs(out)
    for src, dst in COPIED_FILES:
        _copy(src, dst, out)
    for tree in COPIED_TREES:
        for dirpath, dirnames, filenames in os.walk(os.path.join(ROOT, *tree.split("/"))):
            dirnames[:] = sorted(d for d in dirnames if not d.startswith(".") and d != "node_modules"
                                 and d != "__pycache__")
            for name in sorted(filenames):
                rel = os.path.relpath(os.path.join(dirpath, name), ROOT).replace(os.sep, "/")
                if _keep(rel):
                    _copy(rel, rel, out)
    with open(os.path.join(out, "README.md"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write(README)
    _write_symbols(out)
    _annotate_skill(out)
    return sorted(os.path.relpath(os.path.join(d, f), out).replace(os.sep, "/")
                  for d, _, fs in os.walk(out) for f in fs)


def verify(out: str, files: list[str]) -> list[str]:
    """Problems the directory policy would refuse, plus a broken manifest."""
    problems = []
    for rel in files:
        ext = os.path.splitext(rel)[1].lower()
        if not _keep(rel):
            problems.append(f"{rel}: file type not accepted from unverified organizations")
            continue
        with open(os.path.join(out, *rel.split("/")), "rb") as fh:
            data = fh.read()
        if data.startswith(b"#!"):
            problems.append(f"{rel}: starts with #!")
        if ext not in IMAGE_EXT:
            if b"\0" in data:
                problems.append(f"{rel}: contains NUL bytes")
            try:
                data.decode("utf-8")
            except UnicodeDecodeError:
                problems.append(f"{rel}: not UTF-8")
    with open(os.path.join(out, ".claude-plugin", "plugin.json"), encoding="utf-8") as fh:
        manifest = json.load(fh)
    for ref in manifest.get("agents", []) + [manifest.get("icon", "")]:
        if ref and not os.path.isfile(os.path.join(out, *ref.removeprefix("./").split("/"))):
            problems.append(f"plugin.json names {ref}, missing from the edition")
    if not os.path.isfile(os.path.join(out, *SKILL_REL.split("/"), "SKILL.md")):
        problems.append("skill SKILL.md missing")
    if not os.path.isfile(os.path.join(out, *SKILL_REL.split("/"), "references", "limits-and-splitting.md")):
        problems.append("the edition note points at references/limits-and-splitting.md, missing")
    with open(os.path.join(out, *SYMBOLS_REL.split("/"), "index.json"), encoding="utf-8") as fh:
        index = json.load(fh)
    for group in ("methods", "types"):
        for name in index[group]:
            if not os.path.isfile(os.path.join(out, *SYMBOLS_REL.split("/"), group, f"{name}.json")):
                problems.append(f"symbols index names {group}/{name}.json, missing")
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="build into a temp dir and verify")
    sub = parser.add_subparsers(dest="cmd")
    b = sub.add_parser("build", help="write the edition")
    b.add_argument("out")
    args = parser.parse_args(argv)
    if args.check:
        with tempfile.TemporaryDirectory() as tmp:
            out = os.path.join(tmp, "edition")
            problems = verify(out, build(out))
    elif args.cmd == "build":
        out = os.path.abspath(args.out)
        files = build(out)
        problems = verify(out, files)
        print(f"wrote {len(files)} files to {out}")
    else:
        parser.print_help()
        return 2
    for p in problems:
        print(f"FAIL: {p}")
    if not problems and args.check:
        print("OK: directory edition builds and holds only accepted files.")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
